def case(id, topic, title, intro, vit, nodes, src, lvl=3, tags=None):
    d = _base(id, 'case', topic, title, src, lvl)
    d.update(title=title, intro=intro, vit=vit, nodes=nodes, tags=tags or [])
    ids = [n['id'] for n in nodes]
    for i, n in enumerate(nodes):
        if n.get('end'):
            continue
        assert any(c[1] for c in n['ch']), (id, n['id'])
        for c in n['ch']:
            go = c[3] if len(c) > 3 else None
            if go:
                assert go in ids, (id, go)
        if 'next' not in n:
            n['next'] = ids[i + 1]
    return d


def N(id, txt, q, ch, vit=None, next=None):
    """node; ch = list of (text, ok, feedback[, go[, vit]])"""
    d = dict(id=id, txt=txt, q=q, ch=[list(c) for c in ch])
    if vit:
        d['vit'] = vit
    if next:
        d['next'] = next
    return d


def END(txt, vit=None, good=True):
    d = dict(id='end', end=1, txt=txt, good=good)
    if vit:
        d['vit'] = vit
    return d
