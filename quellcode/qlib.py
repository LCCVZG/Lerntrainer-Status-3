def cloze(id, topic, sub, text, gaps, expl, src, lvl=2, memo=None):
    n = text.count('{')
    assert n == len(gaps), id
    d = _base(id, 'cloze', topic, sub, src, lvl, memo)
    d.update(text=text, gaps=gaps, expl=expl)
    return d


